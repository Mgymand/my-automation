def wrap(title, css, body):
    return ('<!doctype html><html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>{title}</title>' + css + '</head><body><div class="sheet">' + body + '</div></body></html>')

def wrap_editable(title, css, body, filename, bar_title):
    ecss, bar, js = editor_parts(filename=filename, title=bar_title)
    full = ('<!doctype html>\n<html lang="ja">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            f'<title>{title}</title>\n' + css + ecss + '</head>\n<body>\n' + bar + '\n<div class="sheet" id="doc">' + body + '</div>\n'
            '<script id="editor-script">' + js + '</script>\n</body>\n</html>\n')
    art = f'<title>{title}</title>' + css + ecss + bar + '<div class="sheet" id="doc">' + body + '</div><script id="editor-script">' + js + '</script>'
    return full, art

