  let n = 0, miss = [];
  for (const [k, v] of Object.entries(V)) {
    const el = document.getElementById("form-field-" + k);
    if (!el) { miss.push(k); continue; }
    el.value = v; fire(el); n++;
  }
  for (const [k, v] of Object.entries(RADIO)) {
    const el = document.querySelector(`input[name="form_fields[${k}]"][value="${v}"]`);
    if (!el) { miss.push(k); continue; }
    el.checked = true; fire(el); n++;
  }
  for (const [k, arr] of Object.entries(CHECK)) {
    for (const v of arr) {
      const el = document.querySelector(`input[name="form_fields[${k}][]"][value="${v}"]`);
      if (!el) { miss.push(k + ":" + v); continue; }
      el.checked = true; fire(el); n++;
    }
  }
  const msg = `入力完了：${n}項目。内容を確認してから「送信する」を押してください。` + (miss.length ? "\n見つからなかった項目: " + miss.join(", ") : "");
  console.log(msg); alert(msg);
